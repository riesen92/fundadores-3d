import { nuevaTarea } from './tasks.ts'
import type { Estrategia, Tarea, Operacion, ConfigBombero } from './tasks.ts'
export function configuracionInicial(): Record<number, ConfigBombero> {
  return Object.fromEntries(Array.from({ length: 8 }, (_, i) => [i + 1, { nombre: `B${i + 1}`, velocidad: 4 }]))
}
