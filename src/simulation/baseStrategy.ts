  add('asegurar', 'asegurarVictima', 1, 'victima', [], [3])
  add('victima-muro', 'transportarVictima', 1, 'muro-i', [], [3])
  add('sostener-muro', 'sostenerCamilla', 3, 'camilla', ['victima-muro'], [], [], 'B3 sostiene la camilla mientras B1 cruza')
