async page => {
  const context = await page.context().browser().newContext({ viewport: { width: 1280, height: 800 } })
  page = await context.newPage(); page.setDefaultTimeout(15000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', event => { if (event.type() === 'error') errors.push(event.text()) })
  try {
    await page.goto('http://127.0.0.1:5173/')
    await page.locator('canvas').waitFor()
    if (!page.url().endsWith('/simulador')) throw Error(`Root did not become /simulador: ${page.url()}`)
    if (await page.locator('.strategy-panel,.task-panel,aside').count()) throw Error('Editor controls are visible in the public simulator')
    const selector = page.getByLabel('Bombero a seguir', { exact: true })
    if (await selector.inputValue() !== '') throw Error('The simulator did not start in general view')
    await selector.selectOption('3')
    if (await selector.inputValue() !== '3') throw Error('Firefighter selection failed')
    const action = page.getByRole('button', { name: '▶ Simular', exact: true })
    if (await action.isDisabled()) throw Error('Official strategy is not ready')
    const restart = page.getByRole('button', { name: '↻ Reiniciar', exact: true })
    if (!await restart.isDisabled()) throw Error('Restart offered before starting')
    const speed = page.getByLabel('Velocidad de reproducción', { exact: true })
    if (await speed.inputValue() !== '1') throw Error('Playback speed did not start at 1x')
    await speed.selectOption('0.5')
    await action.click(); await page.waitForTimeout(200)
    if (await speed.inputValue() !== '0.5') throw Error('Simular reset playback speed')
    await page.evaluate(async () => {
      const { useStrategyStore } = await import('/src/stores/strategy.store.ts'); const store = useStrategyStore()
      for (let i = 0; i < 400 && !store.engine.finalizada && !store.engine.bloqueada; i++) store.engine.tick(.1)
      store.revision++
    })
    await page.waitForTimeout(80)
    if (await page.locator('.simulator-status strong').innerText() === '0.0 s') throw Error('Public clock did not update')
    await page.getByRole('button', { name: 'Pausar', exact: true }).click()
    const time = await page.locator('.simulator-status strong').innerText()
    await page.waitForTimeout(120)
    if (time !== await page.locator('.simulator-status strong').innerText()) throw Error('Pause advanced the public simulation')
    await page.getByRole('button', { name: 'Continuar', exact: true }).click()
    if (await speed.inputValue() !== '0.5') throw Error('Continuar reset playback speed')
    await page.evaluate(async () => {
      const { useStrategyStore } = await import('/src/stores/strategy.store.ts'); const store = useStrategyStore()
      for (let i = 0; i < 15000 && store.reproduciendo; i++) store.tick(.25)
    })
    await page.waitForTimeout(80)
    if (!await page.getByRole('button', { name: '↻ Repetir', exact: true }).isVisible()) throw Error('Completed simulation did not offer replay')
    await speed.selectOption('4')
    await restart.click(); await page.waitForTimeout(200)
    const clock = await page.locator('.simulator-status strong').innerText()
    if (!/^[\d.]+ s$/.test(clock)) throw Error(`Clock unreadable after restart: ${clock}`)
    if (await speed.inputValue() !== '4') throw Error('Restart lost playback speed')
    if (await restart.isDisabled()) throw Error('Restart not available during playback')
    await page.getByRole('button', { name: 'Pausar', exact: true }).click()
    await restart.click(); await page.waitForTimeout(200)
    if (await speed.inputValue() !== '4') throw Error('Restart lost playback speed on pause')
    await speed.selectOption('1')
    if (!await page.getByRole('button', { name: 'Pausar', exact: true }).isVisible()) throw Error('Restart did not start playback')
    const zenital = page.getByRole('button', { name: '▦ Cenital', exact: true })
    await zenital.click()
    if (await zenital.getAttribute('aria-pressed') !== 'true') throw Error('Zenital view failed')
    await page.setViewportSize({ width: 390, height: 844 })
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile simulator overflows')
    await page.setViewportSize({ width: 1280, height: 800 })
    await page.goto('http://127.0.0.1:5173/editor'); await page.locator('canvas').waitFor()
    if (!await page.locator('.strategy-panel').isVisible() || !await page.locator('.task-panel').isVisible()) throw Error('Editor route lost its panels')
    if (!await page.getByRole('link', { name: 'Abrir simulador', exact: true }).isVisible()) throw Error('Editor lacks simulator access')
    if (errors.length) throw Error(errors.join('\n'))
    return { result: 'PASS', checks: 'routes, public controls, firefighter selection, pause/continue, restart, playback speed, zenital, editor, mobile' }
  } finally { await context.close() }
}
