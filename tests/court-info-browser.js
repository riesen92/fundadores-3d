async page => {
  const context = await page.context().browser().newContext({ viewport: { width: 1280, height: 800 } })
  page = await context.newPage(); page.setDefaultTimeout(15000)
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()) })
  try {
    await page.goto('http://127.0.0.1:5173/')
    const canvas = page.locator('canvas'); await canvas.waitFor()
    const opener = page.getByRole('button', { name: 'ⓘ Información de la cancha', exact: true })
    const timeBefore = await page.locator('.simulator-status strong').innerText()
    const drawers = page.locator('.court-drawer')
    if (await drawers.count()) throw Error('Panel opened without user action')
    await opener.click(); await page.waitForTimeout(80)
    if (!await page.getByRole('dialog', { name: 'Información de la cancha', exact: true }).isVisible()) throw Error('Panel did not open')
    const toggle = page.getByRole('checkbox', { name: 'Recorridos de bomberos', exact: true })
    if (await toggle.isChecked()) throw Error('Routes should start hidden')
    await toggle.check(); await page.waitForTimeout(80)
    const hint = page.getByRole('status').filter({ hasText: 'Elige un bombero' })
    if (!await hint.isVisible()) throw Error('General view did not explain tracking for routes')
    const labels = page.locator('.court-drawer').getByRole('checkbox', { name: 'Etiquetas generales', exact: true })
    await labels.uncheck(); await page.waitForTimeout(80)
    const one = await canvas.screenshot(); await labels.check(); await page.waitForTimeout(80)
    if (one.equals(await canvas.screenshot())) throw Error('General labels toggle did not affect the scene')
    await page.locator('.court-drawer-close').click(); await page.waitForTimeout(80)
    if (await drawers.count()) throw Error('Close button did not hide the panel')
    if (await page.locator('.simulator-status strong').innerText() !== timeBefore) throw Error('Opening information controls changed the simulation')
    await opener.click(); await page.waitForTimeout(80)
    await page.getByRole('button', { name: '▶ Simular', exact: true }).click(); await page.waitForTimeout(150)
    const closing = await canvas.screenshot()
    await labels.uncheck(); await page.waitForTimeout(80)
    if (closing.equals(await canvas.screenshot())) throw Error('General labels toggle did not affect the scene during playback')
    await labels.check()
    await page.getByRole('button', { name: 'Pausar', exact: true }).click()
    const clan = page.getByRole('checkbox', { name: 'Cierres perimetrales e interiores', exact: true })
    await clan.uncheck(); await page.waitForTimeout(80)
    const pausedHidden = await canvas.screenshot(); await clan.check(); await page.waitForTimeout(80)
    if (pausedHidden.equals(await canvas.screenshot())) throw Error('Closures toggle did not affect the scene while paused')
    await page.keyboard.press('Escape'); await page.waitForTimeout(80)
    if (await drawers.count()) throw Error('Escape did not hide the panel')
    if (await page.locator('.simulator-status strong').innerText() === timeBefore) throw Error('Simulation clock did not run')
    await page.setViewportSize({ width: 390, height: 844 })
    await opener.click(); await page.waitForTimeout(80)
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile panel overflow')
    if (!await page.locator('.court-drawer-body').evaluate(el => el.scrollHeight > 0)) throw Error('Mobile panel missing scrollable body')
    await page.setViewportSize({ width: 1280, height: 800 })
    await page.goto('http://127.0.0.1:5173/editor'); await canvas.waitFor()
    if (!await page.locator('.court-info').isVisible()) throw Error('Editor lost the information panel')
    await page.getByText('Información de la cancha', { exact: true }).click()
    if (!await page.getByRole('checkbox', { name: 'Etiquetas generales', exact: true }).isVisible()) throw Error('Editor lost the visual toggles')
    if (errors.length) throw Error(errors.join('\n'))
    return { result: 'PASS', checks: 'panel open/close, toggles pre/during/paused, routes hint, escape, camera untouched, editor panel, mobile' }
  } finally { await context.close() }
}
